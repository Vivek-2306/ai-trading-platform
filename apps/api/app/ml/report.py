"""Generate docs/ML_RESEARCH.md from the data (never typed by hand)."""

from pathlib import Path

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.analysis.indicators import CandleSeries
from app.backtest.runner import tuning_candles
from app.backtest.splits import OosKey
from app.data.models import AssetClass
from app.data.universe import InstrumentSpec
from app.ml.evaluate import Evaluation, evaluate_model
from app.ml.protocol import ENTRY_THRESHOLD, FOLD_ARGS, STRATEGY_NAME, SYMBOLS, TIMEFRAMES

OUT = Path(__file__).parents[4] / "docs" / "ML_RESEARCH.md"
_RUNS = text(
    """
    SELECT DISTINCT ON (r.strategy, i.symbol, r.timeframe)
           r.strategy, i.symbol, r.timeframe, r.metrics
    FROM backtest_runs r JOIN instruments i ON i.id = r.instrument_id
    WHERE r.segment = 'tuning' AND r.strategy IN ('rules-v2', 'ml-lgbm-v1')
      AND r.timeframe IN ('1h', '1d') AND i.symbol IN ('BTC/USDT', 'ETH/USDT')
    ORDER BY r.strategy, i.symbol, r.timeframe, r.id DESC
    """
)


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def verdict(evals: dict[tuple[str, str], Evaluation]) -> tuple[bool, list[str]]:
    """The model ships only if it beats the baselines AND clears break-even somewhere. These
    are the tuning-region gates; the locked period is judged only if they pass."""
    reasons = []
    for (symbol, tf), ev in evals.items():
        if not ev.beats_baselines:
            reasons.append(
                f"{symbol} {tf}: Brier {ev.brier_model:.4f} is not better than the base rate"
            )
        best = max((t["win_rate"] or 0.0 for t in ev.thresholds if t["rows"] >= 100), default=0.0)
        if best < ev.breakeven:
            reasons.append(
                f"{symbol} {tf}: best hit rate {best:.1%} is under the {ev.breakeven:.1%} break-even"
            )
    return not reasons, reasons


async def write_report(sessions: async_sessionmaker[AsyncSession]) -> str:
    evals: dict[tuple[str, str], Evaluation] = {}
    for symbol in SYMBOLS:
        for tf in TIMEFRAMES:
            spec = InstrumentSpec("binance", symbol, AssetClass.CRYPTO)
            candles = await tuning_candles(sessions, spec, OosKey(symbol, tf, STRATEGY_NAME))
            train, test = FOLD_ARGS[tf]
            evals[(symbol, tf)], _ = evaluate_model(
                CandleSeries.from_candles(candles), min_train_rows=train, test_rows=test
            )
    async with sessions() as session:
        runs = {(r[0], r[1], r[2]): r[3] for r in (await session.execute(_RUNS)).all()}
    lines = [
        "# ML research report (Phase 10)",
        "",
        "_Generated by `python -m app.ml report` from the stored candles and runs. Everything below"
        " is on the TUNING region; the locked out-of-sample period was not used._",
        "",
        "## Question",
        "",
        "Do LightGBM probabilities (parameters declared in advance, purged walk-forward) predict",
        "whether a 1.6 ATR target is hit before a 1.0 ATR stop, well enough to beat the rules?",
        "",
        "## Does the model know anything?",
        "",
        "| Instrument | TF | Rows scored | AUC | Brier (model) | Brier (base rate) | Brier (coin) | "
        "Calibration error | Break-even win rate |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for (symbol, tf), ev in evals.items():
        lines.append(
            f"| {symbol} | {tf} | {ev.rows} | {ev.auc:.3f} | {ev.brier_model:.4f} | "
            f"{ev.brier_prior:.4f} | {ev.brier_coin:.4f} | {ev.ece_raw:.3f} | {_pct(ev.breakeven)} |"
            if ev.auc is not None
            else f"| {symbol} | {tf} | {ev.rows} | n/a | | | | | |"
        )
    lines += [
        "",
        "AUC of 0.5 is a coin flip; a model that knows something has a Brier score below the",
        "base-rate column. Break-even is the win rate a 1.6:1 trade needs after a 20 bps round trip.",
        "",
        "## Hit rate when the model is confident",
        "",
        "| Instrument | TF | p >= 0.40 | p >= 0.45 | p >= 0.50 | p >= 0.55 | Rules BUY | Break-even |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for (symbol, tf), ev in evals.items():
        cells = " | ".join(f"{_pct(t['win_rate'])} ({t['rows']})" for t in ev.thresholds)
        rules = ev.rules_buy
        lines.append(
            f"| {symbol} | {tf} | {cells} | {_pct(rules.get('win_rate'))} ({rules.get('signals')}) | "
            f"{_pct(ev.breakeven)} |"
        )
    lines += [
        "",
        f"## Backtest on the tuning region (entry when p >= {ENTRY_THRESHOLD:.2f})",
        "",
        "| Instrument | TF | ML trades | ML return | ML profit factor | Rules return | Rules profit factor |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for symbol in SYMBOLS:
        for tf in TIMEFRAMES:
            ml, rules = (
                runs.get((STRATEGY_NAME, symbol, tf), {}),
                runs.get(("rules-v2", symbol, tf), {}),
            )
            lines.append(
                f"| {symbol} | {tf} | {ml.get('trades')} | {ml.get('total_return_pct')}% | "
                f"{ml.get('profit_factor')} | {rules.get('total_return_pct')}% | "
                f"{rules.get('profit_factor')} |"
            )
    ships, reasons = verdict(evals)
    lines += ["", "## Verdict", ""]
    if ships:
        lines.append(
            "The model clears the tuning-region gates. Next step: one judgement of the locked period."
        )
    else:
        lines += [
            "**NO-GO. The model does not ship and is not used for signals.**",
            "",
            "Failed gates:",
            "",
            *[f"- {r}" for r in reasons],
            "",
            "The locked swing out-of-sample period was deliberately NOT spent (owner decision): a",
            "model that fails on tuning data would only burn the one clean test period. It stays",
            "available for a stronger candidate, for example one with news or other data (Phase 11).",
            "",
            "## Caveats",
            "",
            "- 1d has only about 1,750 tuning rows, so its folds and trade counts are small.",
            "- Features are price-only technical indicators; no volume profile, order book, news or",
            "  cross-asset data. A model can only find what is in its inputs.",
            "- Parameters were declared in advance and not tuned; tuning is not expected to turn an",
            "  AUC near 0.50 into a trading edge.",
        ]
    OUT.write_text("\n".join(lines) + "\n")
    return f"wrote {OUT} (ships={ships})"
