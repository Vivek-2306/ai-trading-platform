"""Generate docs/SCALPING_RESEARCH.md from the stored out-of-sample runs (never typed by hand)."""

from pathlib import Path

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.scalping.research import STRATEGIES
from app.scalping.verdict import Verdict, judge, strategy_goes_on

_QUERY = text(
    """
    SELECT DISTINCT ON (r.strategy, i.symbol, r.timeframe)
           r.strategy, i.symbol, r.timeframe, r.metrics, r.details->'cost_drag' AS drag, r.id
    FROM backtest_runs r JOIN instruments i ON i.id = r.instrument_id
    WHERE r.segment = 'oos' AND r.strategy LIKE 'scalp-%'
      AND r.config->>'slippage_bps' = '1' AND r.config->>'fee_pct' = '0.10'
    ORDER BY r.strategy, i.symbol, r.timeframe, r.id DESC
    """
)
OUT = Path(__file__).parents[4] / "docs" / "SCALPING_RESEARCH.md"


async def write_report(sessions: async_sessionmaker[AsyncSession]) -> str:
    async with sessions() as session:
        rows = (await session.execute(_QUERY)).all()
    lines = [
        "# Scalping research report (Phase 9b)",
        "",
        "_Generated by `python -m app.backtest research-report` from stored out-of-sample runs._",
        "",
        "## Pass rules (fixed before the results were read)",
        "",
        "One judgement of the locked out-of-sample period per strategy, instrument and timeframe,",
        "net of costs (0.10% fee each side, 1 bp slippage). A combination passes only with net",
        "return above 0, profit factor of at least 1.2 and at least 30 trades. A strategy goes on",
        "to paper trading only if it passes on both instruments on the same timeframe.",
        "",
        "## Out-of-sample results",
        "",
        "| Strategy | Instrument | TF | Trades | Win % | Profit factor | Net return % | "
        "Gross bps/trade | Fee bps/trade | Result |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    verdicts: dict[str, dict[tuple[str, str], Verdict]] = {s: {} for s in STRATEGIES}
    for strategy, symbol, tf, metrics, drag, _ in rows:
        v = judge(metrics)
        verdicts.setdefault(strategy, {})[(symbol, tf)] = v
        drag = drag or {}
        lines.append(
            f"| {strategy} | {symbol} | {tf} | {metrics.get('trades')} | "
            f"{float(metrics.get('win_rate_pct') or 0):.1f} | "
            f"{float(metrics.get('profit_factor') or 0):.2f} | "
            f"{float(metrics.get('total_return_pct') or 0):.1f} | "
            f"{drag.get('avg_gross_bps_per_trade')} | {drag.get('avg_fee_bps_per_trade')} | "
            f"{'PASS' if v.passed else 'fail: ' + '; '.join(v.failures)} |"
        )
    best = (
        max(float((d or {}).get("avg_gross_bps_per_trade") or 0) for *_, d, _ in rows)
        if rows
        else 0.0
    )
    goes_on = [s for s, per in verdicts.items() if per and strategy_goes_on(per)]
    lines += ["", "## Verdict", ""]
    complete = len(rows) == len(STRATEGIES) * 4
    if goes_on:
        lines.append(
            "Pass the rules (still only paper trading next, never live): " + ", ".join(goes_on)
        )
    elif not complete:
        lines.append(
            f"INCOMPLETE: only {len(rows)} of {len(STRATEGIES) * 4} combinations were judged."
        )
    else:
        lines += [
            "**NO-GO. No scalping strategy passes. None moves to paper trading.**",
            "",
            "Costs are not the whole story: a round trip costs about 20 bps at the regular fee,",
            f"but the best average move before fees is {best:.1f} bps per trade, so the",
            "signals themselves have no edge on this data. Cheaper fee tiers (stored tuning",
            "runs) shrink the losses but none turns them positive. Simple moving-average, VWAP",
            "and breakout rules on 1m/5m BTC and ETH candles are not worth taking further.",
            "",
            "## Caveats",
            "",
            "- 1m history is only about 88 days, so the out-of-sample window is about 18 days.",
            "- Slippage was set to 1 bp and the target to 1.6 ATR after a dry run on the tuning",
            "  region only (reasons in `app/scalping/research.py`); those dry runs stay stored.",
            "- Fee tiers are illustrative; limit entries (maker both ways) were not modelled.",
        ]
    OUT.write_text("\n".join(lines) + "\n")
    return f"wrote {OUT} ({len(rows)} combinations, {len(goes_on)} pass)"
